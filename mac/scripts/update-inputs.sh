#!/bin/sh
# Writes the input file lists Xcode uses to decide when to rerun the scripts that build the Rust
# core: knode-core-inputs.xcfilelist (build-xcframework.sh, package knode-ffi) and
# knode-cli-inputs.xcfilelist (build-knode-cli.sh, package knode-cli). Each list names the
# workspace manifest, Cargo.lock and every source file of the crates of this workspace that the
# package is built from, as `cargo tree` reports them.
#
# Usage: update-inputs.sh            rewrite both lists
#        update-inputs.sh --check [core|cli]
#                                    fail, printing the lines to add or remove, when a list is out
#                                    of date (both lists when none is named)
set -eu

mac_dir="$(cd "$(dirname "$0")/.." && pwd -P)"
# Canonical, because `cargo tree` prints canonical paths.
core_dir="$(cd "$mac_dir/../core" && pwd -P)"

export PATH="${CARGO_HOME:-$HOME/.cargo}/bin:$PATH"
if ! command -v cargo >/dev/null 2>&1; then
    echo "error: cargo not found. Install Rust from https://rustup.rs" >&2
    exit 1
fi

# list <script> <package> [cargo tree options]: the input list of <script>, which builds <package>.
# The Mac target keeps the result the same on every host, so CI can check it on Linux.
list() {
    script="$1"
    package="$2"
    shift 2
    echo "# The files $script is built from: Xcode reruns it when one of them changes."
    echo "# Generated by update-inputs.sh; $script fails when this list is out of date."
    crates="$(cd "$core_dir" && cargo tree --locked --quiet --package "$package" "$@" \
        --target aarch64-apple-darwin \
        --edges normal,build --prefix none \
        | sed -n "s|.*(${core_dir}/\(crates/[^)]*\)).*|\1|p" | sort -u)"
    if [ -z "$crates" ]; then
        echo "error: cargo tree found no crate of the workspace for $package" >&2
        exit 1
    fi
    {
        echo Cargo.lock
        echo Cargo.toml
        # shellcheck disable=SC2086
        (cd "$core_dir" && find $crates -path '*/target' -prune -o -type f \
            \( -path '*/src/*' -o -name Cargo.toml -o -name build.rs -o -name uniffi.toml \) -print)
    } | LC_ALL=C sort -u | sed 's|^|$(SRCROOT)/../core/|'
}

# generate <name>: the input list for core or cli.
generate() {
    case "$1" in
        core) list build-xcframework.sh knode-ffi --features bindgen ;;
        cli) list build-knode-cli.sh knode-cli ;;
        *)
            echo "error: unknown list $1 (expected core or cli)" >&2
            exit 2
            ;;
    esac
}

file_for() {
    echo "$mac_dir/scripts/knode-$1-inputs.xcfilelist"
}

if [ "${1:-}" = "--check" ]; then
    names="${2:-core cli}"
    failed=0
    for name in $names; do
        file="$(file_for "$name")"
        expected="$(generate "$name")"
        if [ "$expected" != "$(cat "$file" 2>/dev/null)" ]; then
            echo "error: mac/scripts/$(basename "$file") is out of date." >&2
            echo "Run mac/scripts/update-inputs.sh, or make these changes:" >&2
            printf '%s\n' "$expected" | grep -v '^#' > "$file.expected.tmp"
            grep -v '^#' "$file" 2>/dev/null | LC_ALL=C sort > "$file.actual.tmp" || true
            LC_ALL=C comm -23 "$file.expected.tmp" "$file.actual.tmp" | sed 's/^/  add: /' >&2
            LC_ALL=C comm -13 "$file.expected.tmp" "$file.actual.tmp" | sed 's/^/  remove: /' >&2
            rm -f "$file.expected.tmp" "$file.actual.tmp"
            failed=1
        fi
    done
    exit "$failed"
fi

for name in core cli; do
    file="$(file_for "$name")"
    generate "$name" > "$file.tmp"
    mv -f "$file.tmp" "$file"
    echo "Wrote mac/scripts/$(basename "$file")"
done
